import assert from 'node:assert/strict';
import fs from 'node:fs';
import { PGlite } from '@electric-sql/pglite';
export async function verifyPhaseC(db) {
  assert.ok(db instanceof PGlite, 'Phase C requires disposable in-memory PGlite');
  let checks = 0;
  const id = n => '00000000-0000-4000-8000-' + String(n).padStart(12, '0');
  const q = async (sql, args) => (await db.query(sql, args)).rows[0];
  const root = () => db.exec("RESET ROLE; SELECT set_config('request.jwt.claim.sub','',false),set_config('request.jwt.claim.role','service_role',false)");
  const as = async n => { await root(); await db.exec(`SELECT set_config('request.jwt.claim.sub','${id(n)}',false),set_config('request.jwt.claim.role','authenticated',false); SET ROLE authenticated`); };
  const reject = async (sql, pattern = /required|permission|owner|unavailable|assigned|current|agreement|acceptance|initial|constraint|immutable|notice/i) => { await assert.rejects(() => db.exec(sql), pattern); checks++; };
  const eq = (a, b) => { assert.deepEqual(a, b); checks++; };
  await root();
  const history = (await db.query('SELECT * FROM private.vendor_legal_acceptances ORDER BY id')).rows;
  const gateway = (await db.query('SELECT * FROM private.gateway_settings ORDER BY provider')).rows;
  const beforeVendors = (await db.query('SELECT * FROM public.vendors ORDER BY id')).rows;
  await db.exec(fs.readFileSync('supabase/migrations/20261026091408_phase_c_vendor_agreement_assignments.sql', 'utf8'));
  eq((await db.query('SELECT * FROM private.vendor_legal_acceptances ORDER BY id')).rows.map(({ assignment_id: _assignment, acknowledgement_text: _acknowledgement, signer_name: _signer, ...r }) => r), history);
  eq((await db.query('SELECT * FROM private.gateway_settings ORDER BY provider')).rows, gateway);
  eq((await db.query('SELECT * FROM public.vendors ORDER BY id')).rows, beforeVendors);
  eq((await q('SELECT vendor_clickwrap_enabled enabled FROM private.commercial_settings')).enabled, false);
  eq(Number((await q('SELECT count(*) n FROM private.vendor_legal_assignments')).n), 0);
  for (const n of [9200, 9201]) await db.query('INSERT INTO auth.users(id,email,raw_user_meta_data) VALUES($1,$2,$3)', [id(n), `phasec${n}@test.invalid`, JSON.stringify({ role: 'vendor', business_name: `Synthetic Phase C ${n}`, business_category: 'Meals' })]);
  const vendor = (await q('SELECT vendor_id id FROM public.profiles WHERE id=$1', [id(9200)])).id;
  const other = (await q('SELECT vendor_id id FROM public.profiles WHERE id=$1', [id(9201)])).id;
  const state = async () => (await q('SELECT public.get_vendor_agreement_state() r')).r;
  await as(9200); eq((await state()).assignment, null);
  await reject("SELECT public.accept_assigned_vendor_agreement(gen_random_uuid(),true)");
  await reject('SELECT * FROM private.vendor_legal_assignments');
  await root(); await db.exec('SET ROLE anon'); await reject('SELECT public.get_vendor_agreement_state()');
  await as(8100); await reject('SELECT public.get_vendor_agreement_state()');
  await root();
  const makeDoc = async (kind, version, scoped = null) => (await q(`INSERT INTO private.legal_versions(kind,version,title,content,content_hash,effective_at,created_by,approved_at,approved_by,vendor_id)
    VALUES($1,$2,'SYNTHETIC TEST ONLY',$3,encode(sha256(convert_to($3,'UTF8')),'hex'),'2025-01-01',$4,now(),$4,$5) RETURNING id`, [kind, version, `SYNTHETIC TEST ONLY. Complete fictional ${kind} ${version}; never a live legal document.`, id(1), scoped])).id;
  const docs = {};
  for (const kind of ['vendor-agreement', 'vendor-fees', 'vendor-standards', 'privacy', 'refund-policy']) docs[kind] = await makeDoc(kind, `phase-c-${kind}`, kind === 'vendor-fees' ? vendor : null);
  const assign = async (basis = 'initial', when = '2025-02-01', changes = {}) => {
    const d = { ...docs, ...changes };
    return (await q(`INSERT INTO private.vendor_legal_assignments(vendor_id,owner_id,agreement_id,schedule_id,standards_id,privacy_id,refunds_id,change_basis,approval_reference,notified_at,effective_at,approved_by)
      VALUES($1,$2,$3,$4,$5,$6,$7,$8,'SYNTHETIC independent legal decision','2025-01-01',$9,$10) RETURNING id`, [vendor, id(9200), d['vendor-agreement'], d['vendor-fees'], d['vendor-standards'], d.privacy, d['refund-policy'], basis, when, id(1)])).id;
  };
  const badSchedule = await makeDoc('vendor-fees', 'phase-c-other-vendor', other);
  await assert.rejects(() => assign('initial', '2025-02-01', { 'vendor-fees': badSchedule }), /vendor-specific/); checks++;
  await assert.rejects(() => assign('informational'), /Initial/); checks++;
  const assignment = await assign();
  await reject(`UPDATE private.legal_versions SET vendor_id='${other}' WHERE id='${docs['vendor-fees']}'`);
  await as(9200);
  const pending = await state();
  eq(pending.requiresAcceptance, true); eq(Object.keys(pending.assignment.documents).length, 5);
  eq(pending.assignment.documents['vendor-fees'].id, docs['vendor-fees']);
  await reject(`SELECT public.accept_assigned_vendor_agreement('${assignment}',true)`);
  await reject(`SELECT public.accept_vendor_legal('${vendor}','{}','[]')`);
  await root();
  // Positive-path enablement is synthetic, confined to this in-memory DB.
  await db.exec('UPDATE private.commercial_settings SET vendor_clickwrap_enabled=true');
  await as(9201); await reject(`SELECT public.accept_assigned_vendor_agreement('${assignment}',true)`);
  eq((await state()).assignment, null);
  await as(9200); await reject(`SELECT public.accept_assigned_vendor_agreement('${assignment}',false)`);
  await reject(`SELECT public.accept_assigned_vendor_agreement('${assignment}',NULL)`);
  const accept = async a => (await q('SELECT public.accept_assigned_vendor_agreement($1,true) r', [a])).r;
  const receipt = await accept(assignment);
  eq((await accept(assignment)).id, receipt.id);
  eq(receipt.vendor_id, vendor); eq(receipt.actor_id, id(9200));
  eq(receipt.method, 'authenticated'); eq(receipt.assignment_id, assignment);
  eq(receipt.signer_name, (await q('SELECT name FROM public.profiles WHERE id=$1', [id(9200)])).name);
  assert.ok(receipt.accepted_at && receipt.acknowledgement_text.includes('authorised')); checks++;
  eq((await state()).requiresAcceptance, false);
  await as(1); await reject(`UPDATE public.vendors SET status='approved' WHERE id='${vendor}'`);
  // Acceptance alone does not satisfy Phase B compliance/bank/schedule review.
  const bank = (await q('SELECT public.submit_vendor_payment_profile($1,$2,true,false) id', [vendor, JSON.stringify({ accountHolder: 'Synthetic Phase C', bank: 'Test bank', accountNumber: '123456789', branchCode: '123456', accountType: 'Current' })])).id;
  await as(8104); await db.query('SELECT public.approve_vendor_payment_profile($1,$2)', [bank, 'SYNTHETIC independent recipient verification']);
  await root();
  const review = async r => db.query(`INSERT INTO private.vendor_activation_reviews(vendor_id,owner_id,acceptance_id,payment_profile_id,compliance_reference,compliance_valid_until,schedules_reference,schedules_hash,reviewed_by)
    VALUES($1,$2,$3,$4,'SYNTHETIC independently verified compliance',now()+interval '1 day','SYNTHETIC executed vendor-specific schedules',$5,$6)`, [vendor, id(9200), r.id, bank, r.documents['vendor-fees'].content_hash, id(1)]);
  await review(receipt);
  await as(1); await db.query("UPDATE public.vendors SET status='approved' WHERE id=$1", [vendor]);
  eq((await q('SELECT status FROM public.vendors WHERE id=$1', [vendor])).status, 'approved');
  await root();
  // Publishing a new global document alone must not force a new contract.
  await makeDoc('vendor-agreement', 'phase-c-unassigned-revision');
  await as(9200); eq((await state()).requiresAcceptance, false);
  await root();
  const newSchedule = await makeDoc('vendor-fees', 'phase-c-material-schedule', vendor);
  const material = await assign('material', '2025-03-01', { 'vendor-fees': newSchedule });
  await assign('informational', '2025-04-01', { 'vendor-fees': newSchedule });
  await as(9200);
  eq((await state()).assignment.id, material); eq((await state()).requiresAcceptance, true);
  await reject(`SELECT public.accept_assigned_vendor_agreement('${assignment}',true)`, /changed/i);
  await as(1); await db.query("UPDATE public.vendors SET status='suspended' WHERE id=$1", [vendor]);
  await reject(`UPDATE public.vendors SET status='approved' WHERE id='${vendor}'`);
  await root(); await db.query("UPDATE public.vendors SET status='pending' WHERE id=$1", [vendor]);
  await as(9200); const materialReceipt = await accept(material);
  eq((await state()).requiresAcceptance, false);
  await as(1); await reject(`UPDATE public.vendors SET status='approved' WHERE id='${vendor}'`);
  await root(); await review(materialReceipt);
  await as(1); await db.query("UPDATE public.vendors SET status='approved' WHERE id=$1", [vendor]);
  await as(9200); const saved = await state(); eq(saved.history.length, 2); eq(saved.requiresAcceptance, false);
  eq(saved.assignment.changeBasis, 'informational');
  await root();
  await reject('UPDATE private.vendor_legal_assignments SET approval_reference=\'Tamper\'');
  await reject('DELETE FROM private.vendor_legal_acceptances');
  await db.query('UPDATE public.profiles SET suspended=true WHERE id=$1', [id(9200)]);
  await as(9200); await reject('SELECT public.get_vendor_agreement_state()');
  await root(); await db.query('UPDATE public.profiles SET suspended=false WHERE id=$1', [id(9200)]);
  await as(9201); eq((await state()).history.length, 0);
  await root(); await db.exec('SET ROLE anon');
  const portal = (await q('SELECT public.get_legal_portal() r')).r;
  assert.notEqual(portal.documents['vendor-fees']?.id, docs['vendor-fees']); checks++;
  assert.notEqual(portal.documents['vendor-fees']?.id, badSchedule); checks++;
  await root();
  const business = (await q('SELECT business FROM private.commercial_settings')).business;
  await db.exec("UPDATE private.commercial_settings SET business=business||'{\"legalNoticeAddress\":\"\"}'::jsonb");
  await as(9200); eq((await state()).businessReady, false);
  await as(1); await db.query("UPDATE public.vendors SET status='suspended' WHERE id=$1", [vendor]);
  await reject(`UPDATE public.vendors SET status='approved' WHERE id='${vendor}'`);
  await root(); await db.query('UPDATE private.commercial_settings SET business=$1', [JSON.stringify(business)]);
  await as(1); await db.query("UPDATE public.vendors SET status='approved' WHERE id=$1", [vendor]);
  await root();
  await db.query('UPDATE private.legal_versions SET approved_at=NULL WHERE id=$1', [docs['vendor-agreement']]);
  await as(9200); const unavailable = await state(); eq(unavailable.assignment.documents, null); eq(unavailable.history.length, 2);
  assert.ok(unavailable.history[0].documents['vendor-agreement'].content.includes('SYNTHETIC')); checks++;
  await root(); await db.query('UPDATE private.legal_versions SET approved_at=now() WHERE id=$1', [docs['vendor-agreement']]);
  await assert.rejects(() => assign('material', '2025-01-02'), /constraint/); checks++;
  const futureDate = new Date(Date.now() + 35 * 86400000).toISOString();
  const future = await assign('material', futureDate, { 'vendor-fees': newSchedule });
  await as(9200); assert.ok((await state()).upcoming); checks++;
  await reject(`SELECT public.accept_assigned_vendor_agreement('${future}',true)`, /changed/i);
  await root();
  eq((await q("SELECT to_regclass('public.vendor_agreement_acceptances') duplicate")).duplicate, null);
  // Generic pre-creation intent must not bypass vendor-specific Phase C review.
  await db.query('INSERT INTO auth.users(id,email,raw_user_meta_data) VALUES($1,$2,$3)', [id(9202), 'generic@test.invalid', JSON.stringify({ role: 'customer' })]);
  const globals = (await q('SELECT private.commercial_documents() docs')).docs;
  const ids = Object.fromEntries(Object.entries(globals).map(([kind, document]) => [kind, document.id]));
  await db.exec('UPDATE private.commercial_settings SET onboarding_enforced=true');
  await as(9202);
  await db.query('SELECT public.prepare_vendor_consent($1,$2)', [JSON.stringify(ids), JSON.stringify(Array(8).fill(true))]);
  const genericVendor = (await q("SELECT public.become_vendor('SYNTHETIC generic applicant','Meals',NULL) r")).r.vendor_id;
  await root(); await db.exec('UPDATE private.commercial_settings SET onboarding_enforced=false');
  const genericReceipt = await q('SELECT * FROM private.vendor_legal_acceptances WHERE vendor_id=$1', [genericVendor]);
  await as(1);
  const genericBank = (await q('SELECT public.submit_vendor_payment_profile($1,$2,true,false) id', [genericVendor, JSON.stringify({ accountHolder: 'Generic fixture', bank: 'Test bank', accountNumber: '123456789', branchCode: '123456', accountType: 'Current' })])).id;
  await as(8104); await db.query('SELECT public.approve_vendor_payment_profile($1,$2)', [genericBank, 'SYNTHETIC independent generic recipient verification']);
  await root();
  await db.query(`INSERT INTO private.vendor_activation_reviews(vendor_id,owner_id,acceptance_id,payment_profile_id,compliance_reference,compliance_valid_until,schedules_reference,schedules_hash,reviewed_by)
    VALUES($1,$2,$3,$4,'SYNTHETIC independently verified compliance',now()+interval '1 day','SYNTHETIC reviewed generic schedule',$5,$6)`, [genericVendor, id(9202), genericReceipt.id, genericBank, genericReceipt.documents['vendor-fees'].content_hash, id(1)]);
  eq((await q('SELECT private.vendor_activation_ready_phase_b($1,$2) ready', [genericVendor, id(9202)])).ready, true);
  eq((await q('SELECT private.vendor_activation_ready($1,$2) ready', [genericVendor, id(9202)])).ready, false);
  await as(1); await reject(`UPDATE public.vendors SET status='approved' WHERE id='${genericVendor}'`);
  await root();
  const settings = (await q('SELECT to_jsonb(s) value FROM private.commercial_settings s')).value;
  await db.exec('DELETE FROM private.commercial_settings');
  await as(9200); eq((await state()).enabled, false); eq((await state()).businessReady, false);
  await reject(`SELECT public.accept_assigned_vendor_agreement('${assignment}',true)`, /not yet available/i);
  await root(); await db.query('INSERT INTO private.commercial_settings SELECT * FROM jsonb_populate_record(NULL::private.commercial_settings,$1)', [JSON.stringify(settings)]);
  console.log(`${checks} Phase C assignment/acceptance/activation/privacy assertions passed in disposable in-memory PGlite. No hosted writes.`);
}
